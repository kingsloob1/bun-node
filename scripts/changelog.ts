#!/usr/bin/env bun
/**
 * Writes the root `CHANGELOG.md` entry for a version from the commit
 * subjects since the previous tag. It writes the file and nothing else: the
 * maintainer reviews the entry and commits it in the version-bump PR.
 *
 * ```bash
 * bun scripts/changelog.ts 3.0.1            # entry from the previous tag to HEAD
 * bun scripts/changelog.ts 3.0.1 --from v3.0.0
 * bun scripts/changelog.ts 3.0.1 --print    # print it, write nothing
 * bun scripts/changelog.ts 3.0.1 --force    # replace a generated entry
 * ```
 *
 * The previous tag is `git describe --tags --abbrev=0`, or the highest `v*`
 * tag when none is reachable. Merge commits are skipped, but a commit a
 * merge brought in links that merge's PR (`Merge pull request #123`), as does
 * a subject ending `(#123)`. Subjects are read as Conventional Commits and
 * grouped by type — Breaking (a `!:` or a `BREAKING CHANGE:` footer),
 * Features, Fixes, Performance, Docs, Other — and, inside each, by scope
 * (`feat(bun-client): …` under bun-client).
 *
 * An entry already in the file is refused. `--force` replaces one this
 * script wrote ({@link GENERATED_MARK}); a hand-written entry
 * ({@link HAND_MARK}, or no mark at all) is never replaced: edit or delete it
 * by hand. `scripts/publish.ts` reads the entry back ({@link entryBody}) for
 * the GitHub release's notes, and refuses to publish a version without one.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import process from "node:process";

/** The comment under the heading of an entry this script wrote; `--force` may replace it. */
export const GENERATED_MARK =
  "<!-- changelog: generated by scripts/changelog.ts; --force regenerates it -->";

/** The comment under the heading of a hand-written entry; this script never replaces it. */
export const HAND_MARK =
  "<!-- changelog: hand-written; scripts/changelog.ts never replaces it -->";

/** The file's opening, written when there is no `CHANGELOG.md` yet. */
export const HEADER = `# Changelog

Every package under \`packages/\` is released together, at one version.
Newest first. \`bun scripts/changelog.ts <version>\` writes an entry from the
commits since the previous tag; \`docs/releasing.md\` is the whole flow.
`;

/** The groups an entry has, in the order they are printed. */
export const GROUPS = [
  "Breaking changes",
  "Features",
  "Fixes",
  "Performance",
  "Docs",
  "Other",
] as const;

/** One of {@link GROUPS}. */
export type Group = (typeof GROUPS)[number];

/** One non-merge commit, as read from git. */
export interface Commit {
  /** Its full hash. */
  hash: string;
  /** Its subject line. */
  subject: string;
  /** Its body (the message after the subject). */
  body: string;
  /** The PR that brought it in, from its subject or its merge, if any. */
  pr?: number;
}

/** A commit read as a Conventional Commit. */
export interface Change {
  /** Where it is listed. */
  group: Group;
  /** Its scope (`bun-client`), or `""` for none. */
  scope: string;
  /** The line's text: the subject's description, plus a `BREAKING CHANGE:` footer's. */
  text: string;
  /** Its PR, if any. */
  pr?: number;
}

const SUBJECT = /^(\w+)(?:\(([^)]*)\))?(!)?:\s*(\S.*)$/;
const TYPE_GROUP: Record<string, Group> = {
  feat: "Features",
  fix: "Fixes",
  perf: "Performance",
  docs: "Docs",
};

/** Reads a commit's subject and body as a {@link Change}. */
export function classify(commit: Commit): Change {
  const subject = commit.subject.replace(/\s*\(#\d+\)\s*$/, "");
  const footer = /^BREAKING[ -]CHANGE:\s*(\S.*)$/m
    .exec(commit.body)?.[1]
    ?.trim();
  const m = SUBJECT.exec(subject);
  const pr = commit.pr ?? prOf(commit.subject);
  if (!m) return { group: "Other", scope: "", text: subject, pr };
  const [, type, scope = "", bang, description] = m;
  const breaking = bang === "!" || footer !== undefined;
  return {
    group: breaking
      ? "Breaking changes"
      : (TYPE_GROUP[type.toLowerCase()] ?? "Other"),
    scope: scope.trim(),
    text:
      footer && footer !== description
        ? `${description} — ${footer}`
        : description,
    pr,
  };
}

/** The PR number a subject names (`(#123)` at its end, or `Merge pull request #123`). */
export function prOf(subject: string): number | undefined {
  const m =
    /\(#(\d+)\)\s*$/.exec(subject) ??
    /^Merge pull request #(\d+)/.exec(subject);
  return m ? Number(m[1]) : undefined;
}

/** The `https://github.com/<owner>/<repo>` of a git remote URL, or `undefined` when it is not GitHub's. */
export function githubUrl(remote: string): string | undefined {
  const m = /github\.com[:/]([^/]+)\/(.+?)(?:\.git)?\/?$/.exec(remote.trim());
  return m ? `https://github.com/${m[1]}/${m[2]}` : undefined;
}

/** What {@link renderEntry} writes. */
export interface EntryInput {
  /** The version the entry is for. */
  version: string;
  /** The entry's date, `YYYY-MM-DD`. */
  date: string;
  /** The previous tag (`v3.0.0`), for the compare link; none for a first release. */
  from?: string;
  /** The commits, newest first as git lists them. */
  commits: Commit[];
  /** The repository's GitHub URL, for PR and compare links. */
  repo?: string;
}

/** The entry's Markdown: heading, {@link GENERATED_MARK}, compare line, then each non-empty group by scope. */
export function renderEntry(input: EntryInput): string {
  const changes = [...input.commits].reverse().map(classify);
  const link = (pr?: number) =>
    pr === undefined
      ? ""
      : input.repo
        ? ` ([#${pr}](${input.repo}/pull/${pr}))`
        : ` (#${pr})`;
  const lines = [`## ${input.version} (${input.date})`, "", GENERATED_MARK, ""];
  const tag = `v${input.version}`;
  if (input.from)
    lines.push(
      input.repo
        ? `Changes since ${input.from} ([compare](${input.repo}/compare/${input.from}...${tag})).`
        : `Changes since ${input.from}.`,
      "",
    );
  if (changes.length === 0) lines.push("No changes.", "");
  for (const group of GROUPS) {
    const inGroup = changes.filter((c) => c.group === group);
    if (inGroup.length === 0) continue;
    lines.push(`### ${group}`, "");
    const scopes = [...new Set(inGroup.map((c) => c.scope))].sort((a, b) =>
      a === "" ? -1 : b === "" ? 1 : a.localeCompare(b),
    );
    for (const scope of scopes) {
      const items = inGroup.filter((c) => c.scope === scope);
      if (scope === "") {
        for (const c of items) lines.push(`- ${c.text}${link(c.pr)}`);
        continue;
      }
      lines.push(`- **${scope}**`);
      for (const c of items) lines.push(`  - ${c.text}${link(c.pr)}`);
    }
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

/** Where an entry sits in the file. */
export interface EntryLocation {
  /** The offset of its heading. */
  start: number;
  /** The offset just past it: the next `## ` heading, or the end. */
  end: number;
  /** Its text, heading included. */
  text: string;
  /** True when it carries {@link GENERATED_MARK}. */
  generated: boolean;
}

/** Escapes a string for a regular expression. */
function escape(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/** The version's entry (`## 3.0.0`, `## [3.0.0]`, `## v3.0.0`), or `undefined`. */
export function findEntry(
  changelog: string,
  version: string,
): EntryLocation | undefined {
  const heading = new RegExp(
    `^## \\[?v?${escape(version)}\\]?(?=[\\s(]|$)`,
    "m",
  );
  const m = heading.exec(changelog);
  if (!m) return undefined;
  const after = changelog.slice(m.index + m[0].length);
  const next = /^## /m.exec(after);
  const end = next ? m.index + m[0].length + next.index : changelog.length;
  const text = changelog.slice(m.index, end);
  return {
    start: m.index,
    end,
    text,
    generated: text.includes(GENERATED_MARK),
  };
}

/** The version's entry without its heading and mark: the GitHub release's notes. `undefined` when there is none. */
export function entryBody(
  changelog: string,
  version: string,
): string | undefined {
  const entry = findEntry(changelog, version);
  if (!entry) return undefined;
  return entry.text
    .split("\n")
    .slice(1)
    .filter((l) => l.trim() !== GENERATED_MARK && l.trim() !== HAND_MARK)
    .join("\n")
    .trim();
}

/** Refused: the version's entry exists and may not be replaced. */
export class EntryExists extends Error {
  /** @param message - Why, and what to do. */
  constructor(message: string) {
    super(message);
    this.name = "EntryExists";
  }
}

/**
 * The changelog with `entry` for `version` added, newest first: after the
 * file's opening, before the first entry. Throws {@link EntryExists} when the
 * version has an entry, unless `force` and that entry is a generated one.
 */
export function insertEntry(
  changelog: string | undefined,
  version: string,
  entry: string,
  force = false,
): string {
  const text = changelog ?? HEADER;
  const existing = findEntry(text, version);
  if (existing) {
    if (!existing.generated)
      throw new EntryExists(
        `CHANGELOG.md already has a hand-written entry for ${version}; edit it by hand (--force replaces only a generated one)`,
      );
    if (!force)
      throw new EntryExists(
        `CHANGELOG.md already has an entry for ${version}; --force replaces it`,
      );
    return `${text.slice(0, existing.start)}${entry}\n${text.slice(existing.end).replace(/^\n+/, "")}`.replace(
      /\n+$/,
      "\n",
    );
  }
  const first = /^## /m.exec(text);
  if (!first) return `${text.trimEnd()}\n\n${entry}`;
  return `${text.slice(0, first.index)}${entry}\n${text.slice(first.index)}`;
}

/** Runs git in `cwd`; its stdout, or a thrown error carrying its output. */
function git(cwd: string, args: string[]): string {
  const r = Bun.spawnSync({
    cmd: ["git", ...args],
    cwd,
    stdout: "pipe",
    stderr: "pipe",
  });
  if (r.exitCode !== 0)
    throw new Error(`git ${args.join(" ")} failed:\n${r.stderr.toString()}`);
  return r.stdout.toString();
}

/** The tag entries start from: `git describe --tags --abbrev=0`, else the highest `v*` tag, else none. */
export function previousTag(cwd: string): string | undefined {
  try {
    return git(cwd, ["describe", "--tags", "--abbrev=0"]).trim() || undefined;
  } catch {
    const tags = git(cwd, ["tag", "--list", "v*"])
      .split("\n")
      .map((t) => t.trim())
      .filter((t) => /^v\d+\.\d+\.\d+/.test(t));
    tags.sort((a, b) => Bun.semver.order(a.slice(1), b.slice(1)));
    return tags.at(-1);
  }
}

/**
 * The non-merge commits in `from..to` (all of `to` without `from`), newest
 * first, each with the PR that brought it in: its own `(#123)`, else the
 * oldest merge in the range whose subject names a PR and whose second
 * parent's side holds it.
 */
export function collectCommits(
  cwd: string,
  from: string | undefined,
  to = "HEAD",
): Commit[] {
  const range = from ? `${from}..${to}` : to;
  const raw = git(cwd, ["log", "--format=%H%x1f%P%x1f%s%x1f%b%x1e", range]);
  const commits: Commit[] = [];
  const merges: { hash: string; parents: string[]; pr: number }[] = [];
  for (const record of raw.split("\x1E")) {
    const [hash, parents, subject, body] = record
      .replace(/^\n/, "")
      .split("\x1F");
    if (!hash) continue;
    const ps = parents.trim().split(" ").filter(Boolean);
    if (ps.length > 1) {
      const pr = prOf(subject);
      if (pr !== undefined) merges.push({ hash, parents: ps, pr });
      continue;
    }
    commits.push({ hash, subject, body: body ?? "", pr: prOf(subject) });
  }
  const byHash = new Map(commits.map((c) => [c.hash, c]));
  for (const merge of merges.reverse()) {
    const side = git(cwd, [
      "rev-list",
      `${merge.parents[0]}..${merge.parents[1]}`,
    ])
      .split("\n")
      .filter(Boolean);
    for (const hash of side) {
      const c = byHash.get(hash);
      if (c && c.pr === undefined) c.pr = merge.pr;
    }
  }
  return commits;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const version = args.find((a) => !a.startsWith("--"));
  const option = (name: string) => {
    const i = args.indexOf(name);
    return i === -1 ? undefined : args[i + 1];
  };
  if (!version || !/^\d+\.\d+\.\d+(?:-[\w.]+)?$/.test(version)) {
    console.error(
      "usage: bun scripts/changelog.ts <version> [--from <tag>] [--print] [--force]",
    );
    process.exit(2);
  }
  const root = resolve(import.meta.dir, "..");
  const from = option("--from") ?? previousTag(root);
  let repo: string | undefined;
  try {
    repo = githubUrl(git(root, ["remote", "get-url", "origin"]));
  } catch {
    repo = undefined;
  }
  const commits = collectCommits(root, from);
  const entry = renderEntry({
    version,
    date: new Date().toISOString().slice(0, 10),
    from,
    commits,
    repo,
  });
  if (args.includes("--print")) {
    process.stdout.write(entry);
    process.exit(0);
  }
  const path = join(root, "CHANGELOG.md");
  try {
    const next = insertEntry(
      existsSync(path) ? readFileSync(path, "utf8") : undefined,
      version,
      entry,
      args.includes("--force"),
    );
    writeFileSync(path, next);
  } catch (error) {
    if (!(error instanceof EntryExists)) throw error;
    console.error(error.message);
    process.exit(1);
  }
  console.log(
    `CHANGELOG.md: ${version}, ${commits.length} commit(s) since ${from ?? "the start"}. Review it and commit it in the version-bump PR.`,
  );
}
